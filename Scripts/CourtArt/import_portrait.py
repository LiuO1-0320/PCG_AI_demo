"""Import and validate only the portrait assets. Runs in the UE Python commandlet."""
from pathlib import Path
import unreal as ue

ROOT = '/Game/Demo/CourtArt/Portraits'
SOURCE = Path(ue.Paths.convert_relative_path_to_full(ue.Paths.project_dir()))/'Saved/CourtArtSource'
ea = ue.EditorAssetLibrary
assets = ue.AssetToolsHelpers.get_asset_tools()
mel = ue.MaterialEditingLibrary
ea.make_directory(ROOT)


def load_or_import(name, ext, cls):
    path = ROOT+'/'+name
    if ea.does_asset_exist(path):
        return ea.load_asset(path)
    task = ue.AssetImportTask()
    for setting, value in dict(filename=str(SOURCE/(name+ext)), destination_path=ROOT, destination_name=name,
                               automated=True, replace_existing=False, save=False).items():
        task.set_editor_property(setting, value)
    assets.import_asset_tasks([task])
    result = task.get_objects()
    item = next((o for o in result if isinstance(o, cls) and o.get_name()==name), None)
    assert item, (name,[o.get_path_name() for o in result])
    # Do not write any materials or intermediary scene objects generated by Interchange.
    if item.get_path_name()!=path+'.'+name:
        item = assets.duplicate_asset(name, ROOT, item)
    assert item and item.get_path_name()==path+'.'+name, name
    return item


def linear(hexcolor):
    c = [int(hexcolor[i:i+2],16)/255 for i in (0,2,4)]
    return ue.LinearColor(*(v/12.92 if v<.04045 else ((v+.055)/1.055)**2.4 for v in c), 1.)


def create_material(name, metallic, roughness, colors=None, portrait=None):
    path = ROOT+'/'+name
    mat = ea.load_asset(path) if ea.does_asset_exist(path) else assets.create_asset(name, ROOT, ue.Material, ue.MaterialFactoryNew())
    assert mat
    mel.delete_all_material_expressions(mat)
    mat.set_editor_property('two_sided', True)
    for flag in (ue.MaterialUsage.MATUSAGE_INSTANCED_STATIC_MESHES, ue.MaterialUsage.MATUSAGE_NANITE):
        mel.set_base_material_usage(mat,flag,True)
        assert mel.has_material_usage(mat,flag), (path,flag)

    def node(kind,x,y):
        return mel.create_material_expression(mat,kind,x,y)

    def scalar(value,x,y):
        n = node(ue.MaterialExpressionConstant,x,y)
        n.set_editor_property('r',value)
        return n

    if portrait:
        tex = node(ue.MaterialExpressionTextureSample,-540,-240)
        tex.set_editor_property('texture',portrait)
        base = node(ue.MaterialExpressionMultiply,-290,-240)
        base.set_editor_property('const_b',.94)
        assert mel.connect_material_expressions(tex,'RGB',base,'A')
    else:
        tex = node(ue.MaterialExpressionTextureSample,-620,-340)
        tex.set_editor_property('texture',patina)
        tex.set_editor_property('sampler_type',ue.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
        base = node(ue.MaterialExpressionLinearInterpolate,-270,-220)
        assert mel.connect_material_expressions(tex,'R',base,'Alpha')
        for i, color in enumerate(colors):
            n = node(ue.MaterialExpressionConstant3Vector,-620,-150+i*110)
            n.set_editor_property('constant',linear(color))
            assert mel.connect_material_expressions(n,'',base,'AB'[i])
    assert mel.connect_material_property(base,'',ue.MaterialProperty.MP_BASE_COLOR)
    assert mel.connect_material_property(scalar(metallic,-250,30),'',ue.MaterialProperty.MP_METALLIC)
    assert mel.connect_material_property(scalar(roughness,-250,145),'',ue.MaterialProperty.MP_ROUGHNESS)
    assert mel.get_material_property_input_node(mat,ue.MaterialProperty.MP_EMISSIVE_COLOR) is None
    mel.recompile_material(mat)
    assert ea.save_loaded_asset(mat,False), path
    return mat


